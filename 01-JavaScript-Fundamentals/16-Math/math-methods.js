// Rounding numbers

const decimalValue = 4.7

console.log(Math.round(decimalValue))
console.log(Math.floor(decimalValue))
console.log(Math.ceil(decimalValue))
console.log(Math.trunc(decimalValue))


// Absolute value

const negativeValue = -25

console.log(Math.abs(negativeValue))


// Powers and square root

console.log(Math.pow(2, 3))
console.log(Math.sqrt(64))


// Maximum and minimum

console.log(Math.max(10, 25, 5, 40))
console.log(Math.min(10, 25, 5, 40))


// Random number

console.log(Math.random())


// Random integer between 1 and 10

const randomNumber = Math.floor(Math.random() * 10) + 1

console.log(randomNumber)


// Mathematical constants

console.log(Math.PI)