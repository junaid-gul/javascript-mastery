const firstValue = 10
const secondValue = 20

console.log('Equal:', firstValue == secondValue)
console.log('Not equal:', firstValue != secondValue)
console.log('Strict equal:', firstValue === secondValue)
console.log('Strict not equal:', firstValue !== secondValue)
console.log('Greater than:', firstValue > secondValue)
console.log('Less than:', firstValue < secondValue)
console.log('Greater or equal:', firstValue >= secondValue)
console.log('Less or equal:', firstValue <= secondValue)